#[inline(always)]
pub fn malloc<T>() -> *mut T {
    unsafe { crate::ffi::commonlib_malloc(core::mem::size_of::<T>()) as *mut T }
}

#[inline(always)]
pub fn free<T>(ptr: *mut T) {
    unsafe { crate::ffi::commonlib_free(ptr as *mut _) }
}

